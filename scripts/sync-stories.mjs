// Copies story info from the Flutter app into src/stories.js.
// Only the opening of each story is included, as a taster for the website.
// Run with: npm run sync-stories
import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../../assets/data/stories.json', import.meta.url);
const target = new URL('../src/stories.js', import.meta.url);

const PREVIEW_SHARE = 0.35; // fraction of the story to show
const PREVIEW_MAX_CHARS = 900;

const stories = JSON.parse(readFileSync(source, 'utf8')).map((s) => {
  const paragraphs = s.storyText.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean);
  const total = paragraphs.reduce((n, p) => n + p.length, 0);
  const budget = Math.min(total * PREVIEW_SHARE, PREVIEW_MAX_CHARS);
  const preview = [];
  let used = 0;
  for (const p of paragraphs) {
    if (preview.length >= 4 && used + p.length > budget) break;
    preview.push(p);
    used += p.length;
  }
  return {
    id: s.id,
    title: s.title,
    description: s.description,
    category: s.category,
    image: s.imagePath,
    preview,
  };
});

writeFileSync(
  target,
  `// Generated by scripts/sync-stories.mjs from ../assets/data/stories.json. Do not edit by hand.\n` +
    `export const stories = ${JSON.stringify(stories, null, 2)};\n`,
);
console.log(`Wrote ${stories.length} stories to src/stories.js`);
